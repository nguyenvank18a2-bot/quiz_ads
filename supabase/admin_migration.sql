create or replace function public.claim_reward()
returns integer language plpgsql security definer set search_path = '' as $$
declare new_balance integer; reward_amount integer;
begin
  if (select auth.uid()) is null then raise exception 'Authentication required'; end if;
  if exists(select 1 from public.profiles where id=(select auth.uid()) and is_banned) then raise exception 'Account is locked'; end if;
  select coalesce((value #>> '{}')::integer, 10) into reward_amount from public.app_settings where key='reward_icons';
  update public.profiles set icon_balance = icon_balance + coalesce(reward_amount,10)
  where id = (select auth.uid()) returning icon_balance into new_balance;
  if new_balance is null then raise exception 'Profile not found'; end if;
  return new_balance;
end;
$$;

create or replace function public.unlock_question(target_question_id bigint)
returns integer language plpgsql security definer set search_path = '' as $$
declare current_balance integer; question_order integer; unlock_price integer; free_limit integer;
begin
  if (select auth.uid()) is null then raise exception 'Authentication required'; end if;
  if exists(select 1 from public.profiles where id=(select auth.uid()) and is_banned) then raise exception 'Account is locked'; end if;
  select sort_order into question_order from public.questions where id=target_question_id and status='published';
  if question_order is null then raise exception 'Question not found'; end if;
  select coalesce((value #>> '{}')::integer,20) into unlock_price from public.app_settings where key='unlock_cost';
  select coalesce((value #>> '{}')::integer,10) into free_limit from public.app_settings where key='free_question_limit';
  select icon_balance into current_balance from public.profiles where id=(select auth.uid()) for update;
  if question_order <= coalesce(free_limit,10) then return current_balance; end if;
  if exists(select 1 from public.user_unlocks where user_id=(select auth.uid()) and question_id=target_question_id) then return current_balance; end if;
  if current_balance < coalesce(unlock_price,20) then raise exception 'Not enough icons'; end if;
  insert into public.user_unlocks(user_id,question_id) values((select auth.uid()),target_question_id);
  update public.profiles set icon_balance=icon_balance-coalesce(unlock_price,20)
  where id=(select auth.uid()) returning icon_balance into current_balance;
  return current_balance;
end;
$$;

create or replace function public.submit_answer(target_question_id bigint, chosen_answer integer)
returns boolean language plpgsql security definer set search_path = '' as $$
declare answer_index integer; answer_is_correct boolean; question_order integer; free_limit integer;
begin
  if (select auth.uid()) is null then raise exception 'Authentication required'; end if;
  if exists(select 1 from public.profiles where id=(select auth.uid()) and is_banned) then raise exception 'Account is locked'; end if;
  if chosen_answer < 0 or chosen_answer > 3 then raise exception 'Invalid answer'; end if;
  select correct_answer,sort_order into answer_index,question_order from public.questions where id=target_question_id and status='published';
  if answer_index is null then raise exception 'Question not found'; end if;
  select coalesce((value #>> '{}')::integer,10) into free_limit from public.app_settings where key='free_question_limit';
  if question_order > coalesce(free_limit,10) and not exists(select 1 from public.user_unlocks where user_id=(select auth.uid()) and question_id=target_question_id) then raise exception 'Question is locked'; end if;
  answer_is_correct := chosen_answer=answer_index;
  insert into public.user_progress(user_id,question_id,selected_answer,is_correct,completed_at)
  values((select auth.uid()),target_question_id,chosen_answer,answer_is_correct,now())
  on conflict(user_id,question_id) do update set selected_answer=excluded.selected_answer,is_correct=excluded.is_correct,completed_at=excluded.completed_at;
  return answer_is_correct;
end;
$$;

create or replace function public.admin_dashboard()
returns jsonb language sql stable security definer set search_path = '' as $$
  select case when public.is_admin() then jsonb_build_object(
    'users',(select count(*) from auth.users where deleted_at is null),
    'questions',(select count(*) from public.questions),
    'categories',(select count(*) from public.categories),
    'published',(select count(*) from public.questions where status='published'),
    'inactive_questions',(select count(*) from public.questions where status<>'published'),
    'answers',(select count(*) from public.user_progress)
  ) else (select null::jsonb) end
$$;

create or replace function public.admin_list_users()
returns table(id uuid,email text,display_name text,role text,icon_balance integer,is_banned boolean,created_at timestamptz,completed_count bigint)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  return query select u.id,u.email::text,p.display_name,p.role,p.icon_balance,p.is_banned,p.created_at,
    (select count(*) from public.user_progress up where up.user_id=u.id)
  from auth.users u join public.profiles p on p.id=u.id where u.deleted_at is null order by p.created_at desc;
end $$;

create or replace function public.admin_set_user_icons(target_user_id uuid,new_balance integer)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if new_balance < 0 then raise exception 'Invalid balance'; end if;
  update public.profiles set icon_balance=new_balance where id=target_user_id;
end $$;

create or replace function public.admin_set_user_banned(target_user_id uuid,banned boolean)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if target_user_id=(select auth.uid()) then raise exception 'Cannot lock your own account'; end if;
  update public.profiles set is_banned=banned where id=target_user_id;
  update auth.users set banned_until=case when banned then now()+interval '100 years' else null end,updated_at=now() where id=target_user_id;
end $$;

