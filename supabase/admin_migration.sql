create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'admin' and not is_banned)
$$;

create or replace function public.sync_question_category()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.category_id is not null then
    select name into new.category from public.categories where id = new.category_id;
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists sync_question_category_trigger on public.questions;
create trigger sync_question_category_trigger before insert or update on public.questions
for each row execute function public.sync_question_category();

create or replace function public.sync_category_name()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.questions set category = new.name where category_id = new.id;
  update public.categories set updated_at = now() where id = new.id and updated_at = old.updated_at;
  return new;
end $$;

drop trigger if exists sync_category_name_trigger on public.categories;
create trigger sync_category_name_trigger after update of name on public.categories
for each row execute function public.sync_category_name();

