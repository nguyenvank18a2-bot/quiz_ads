create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.categories(name)
select distinct trim(category) from public.questions
where trim(category) <> ''
on conflict (name) do nothing;

alter table public.questions
  add column if not exists category_id bigint references public.categories(id) on delete restrict,
  add column if not exists difficulty text not null default 'medium',
  add column if not exists status text not null default 'published',
  add column if not exists updated_at timestamptz not null default now();

do $$ begin
  alter table public.questions add constraint questions_difficulty_check check (difficulty in ('easy', 'medium', 'hard'));
exception when duplicate_object then null;
end $$;
do $$ begin
  alter table public.questions add constraint questions_status_check check (status in ('published', 'draft', 'hidden'));
exception when duplicate_object then null;
end $$;

update public.questions q set category_id = c.id
from public.categories c where c.name = q.category and q.category_id is null;

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null,
  label text not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

